public class ExpressoesComparativas {
    public static void main(String[] args) {

        int pao = 10;
        int acucar = 20;

        System.out.println("\n");

        System.out.println("O valor de pão é de R$ " + pao + " e o valor de açucar é de R$ " + acucar);

        System.out.println("========================================================\n");


        System.out.println("O valor de pão é igual que açucar? " + (pao == acucar));
        System.out.println("O valor de pão é diferente que açucar? " + (pao != acucar));
        System.out.println("O valor de pão é maior que acucar? " + (pao > acucar));
        System.out.println("O valor de pão é menor que acuçar? " + (pao < acucar));
        System.out.println("O valor de pão é maior que igual que açucar? " + (pao >= acucar));
        System.out.println("O valor de pão é menor que igual que açucar? " + (pao <= acucar));


    }
}
